// Builds specimen.html from results.json (run crossing-benchmark.mjs first).
// Static SVG, no dependencies, no fetch — data is inlined so the file opens
// standalone from file://.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const dir = dirname(fileURLToPath(import.meta.url))
const data = JSON.parse(readFileSync(join(dir, 'results.json'), 'utf8'))

function svg(positions, links, { w = 360, h = 300, title }) {
  const pad = 24
  const sx = (x) => pad + (x / 100) * (w - 2 * pad)
  const sy = (y) => pad + (y / 100) * (h - 2 * pad)
  const edges = links
    .filter((l) => positions[l.from] && positions[l.to] && l.from !== l.to)
    .map((l) => {
      const a = positions[l.from], b = positions[l.to]
      return `<line x1="${sx(a.x).toFixed(1)}" y1="${sy(a.y).toFixed(1)}" x2="${sx(b.x).toFixed(1)}" y2="${sy(b.y).toFixed(1)}" stroke="#94a3b8" stroke-width="1.5" />`
    })
    .join('\n')
  const nodes = Object.entries(positions)
    .map(([id, p]) => `
      <circle cx="${sx(p.x).toFixed(1)}" cy="${sy(p.y).toFixed(1)}" r="9" fill="#0f172a" stroke="#fff" stroke-width="1.5" />
      <text x="${sx(p.x).toFixed(1)}" y="${(sy(p.y) + 22).toFixed(1)}" font-size="10" text-anchor="middle" fill="#334155" font-family="ui-monospace, monospace">${id}</text>
    `)
    .join('\n')
  return `
    <figure style="margin:0">
      <figcaption style="font:600 12px system-ui; margin-bottom:4px; color:#0f172a">${title}</figcaption>
      <svg width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" style="background:#f8fafc; border:1px solid #e2e8f0; border-radius:8px">
        ${edges}
        ${nodes}
      </svg>
    </figure>
  `
}

const sections = []
sections.push({
  key: 'A_clean_tree',
  heading: 'A — clean tree (7 nodes, no cross-links): 0 → 0 crossings, 0 overlaps either way',
  panels: [
    svg(data.A_clean_tree.current, data.A_clean_tree.links, { title: 'current (layoutBoardDraft)' }),
    svg(data.A_clean_tree.barycenter, data.A_clean_tree.links, { title: 'layered + barycenter + local search' }),
  ],
})
sections.push({
  key: 'B_brainstorm_12node_crosslinks',
  heading: 'B — 12-node brainstorm, realistic cross-branch links: 8 → 4 crossings, edge length 428.6 → 380.8',
  panels: [
    svg(data.B_brainstorm_12node_crosslinks.current, data.B_brainstorm_12node_crosslinks.links, { title: 'current (layoutBoardDraft): 8 crossings' }),
    svg(data.B_brainstorm_12node_crosslinks.barycenter, data.B_brainstorm_12node_crosslinks.links, { title: 'layered + barycenter + local search: 4 crossings' }),
  ],
})
sections.push({
  key: 'C_cycle_plus_island',
  heading: 'C — feedback cycle + disconnected pair: current stacks 5 nodes at the exact same point (10 overlapping pairs); force-directed has 0 overlaps',
  panels: [
    svg(data.C_cycle_plus_island.current, data.C_cycle_plus_island.links, { title: 'current (layoutBoardDraft): 10 overlapping pairs — h4..h8 at the identical point' }),
    svg(data.C_cycle_plus_island.force, data.C_cycle_plus_island.links, { title: 'force-directed, 500 iter: 0 overlaps, 1 crossing' }),
  ],
})

const html = `<!doctype html>
<html lang="en"><head><meta charset="utf-8" />
<title>KIRA auto-organize: before/after specimen</title>
<style>
  body { font: 14px system-ui; margin: 24px; background: #fff; color: #0f172a; }
  h1 { font-size: 16px; margin-bottom: 4px; }
  p.sub { color: #64748b; margin-top: 0; }
  section { margin: 28px 0; }
  h2 { font-size: 13px; font-weight: 600; margin-bottom: 10px; }
  .row { display: flex; gap: 16px; flex-wrap: wrap; }
</style>
</head><body>
  <h1>KIRA auto-organize layout: before / after, 3 fixtures</h1>
  <p class="sub">Generated by build-specimen.mjs from results.json (crossing-benchmark.mjs output). See docs/research/2026-11-07-auto-organize-layout.md §4 for the full numbers and method.</p>
  ${sections.map((s) => `
    <section>
      <h2>${s.heading}</h2>
      <div class="row">${s.panels.join('')}</div>
    </section>
  `).join('')}
</body></html>`

writeFileSync(join(dir, 'specimen.html'), html)
console.log('Wrote specimen.html')
